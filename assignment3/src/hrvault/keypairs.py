# Storage of each user's RSA key pair and certificate.

"""Each user's RSA key pair and certificate, stored next to the account.

The public key and the self-signed certificate are stored in clear so
that others can encrypt for the user and check their signatures. The
private key is sealed with the owner's AES subkey and bound to the
context ``user:<id>|rsa-private-key``, so a sealed key copied onto
another account does not open.

A key pair is either generated by the server or imported by the user
(see `key_import.py`); `origin` records which.
"""

import sqlite3

from Crypto.PublicKey import RSA

from .crypto import rsa_keys
from .owner import Owner
from .pdfsign import certificate, certificate_info

PRIVATE_KEY_ITEM = "rsa-private-key"
INSERT_KEYS = """
INSERT INTO user_keys (user_id, public_key, private_key, certificate, origin)
VALUES (?, ?, ?, ?, ?)
"""


def _row(conn: sqlite3.Connection, user_id: int):
    """The user's key row, or None if the user has no key pair."""
    return conn.execute("SELECT * FROM user_keys WHERE user_id = ?",
                        (user_id,)).fetchone()


def public_key_of(conn: sqlite3.Connection, user_id: int) -> bytes | None:
    """The user's DER public key, or None if the user has no key pair."""
    row = _row(conn, user_id)
    if row is None:
        return None
    return row["public_key"]


def store_key_pair(owner: Owner, key: RSA.RsaKey, origin: str) -> None:
    """Seal and store a private key with a new certificate for it."""
    username = owner.conn.execute("SELECT username FROM users WHERE id = ?",
                                  (owner.user_id,)).fetchone()["username"]
    sealed = rsa_keys.seal_private(owner.keys, key,
                                   owner.context(PRIVATE_KEY_ITEM))
    owner.conn.execute(INSERT_KEYS, (
        owner.user_id, rsa_keys.public_der(key), sealed,
        certificate.create(key, username), origin))
    owner.conn.commit()


def ensure_key_pair(owner: Owner, bits: int) -> bool:
    """Generate the owner's key pair if missing; True if one was made."""
    if _row(owner.conn, owner.user_id) is not None:
        return False
    store_key_pair(owner, rsa_keys.generate(bits), "generated")
    return True


def load_private_key(owner: Owner):
    """Open the owner's private key; None if the owner has no key pair."""
    row = _row(owner.conn, owner.user_id)
    if row is None:
        return None
    context = owner.context(PRIVATE_KEY_ITEM)
    return rsa_keys.open_private(owner.keys, row["private_key"], context)


def certificate_of(conn: sqlite3.Connection, user_id: int) -> bytes | None:
    """The user's DER certificate, or None if they have no key pair."""
    row = _row(conn, user_id)
    if row is None:
        return None
    return row["certificate"]


def key_info(conn: sqlite3.Connection, user_id: int) -> dict | None:
    """Fingerprint, size, origin and certificate dates of the key."""
    row = _row(conn, user_id)
    if row is None:
        return None
    cert = certificate_info.parse(row["certificate"])
    return {"fingerprint": rsa_keys.fingerprint(row["public_key"]),
            "bits": rsa_keys.key_bits(row["public_key"]),
            "origin": row["origin"], "created_at": row["created_at"],
            "subject": cert.subject, "not_after": cert.not_after}


def username_for_key(conn: sqlite3.Connection, public_key: bytes):
    """The employee number whose stored public key this is, or None."""
    row = conn.execute(
        "SELECT u.username FROM user_keys k JOIN users u ON u.id = k.user_id"
        " WHERE k.public_key = ?", (public_key,)).fetchone()
    if row is None:
        return None
    return row["username"]
